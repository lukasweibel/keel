#!/usr/bin/env bash
# Syncs skills, commands and agents from this repo to Claude Code and OpenCode.
#
# Usage:  ./sync.sh [claude|opencode|both]     default: both
#         COPY=1 ./sync.sh                     copy instead of symlink
#
# Skills and commands are symlinked, so changes in the repo apply right away.
# Agents with a head file are assembled. Run again after changing an agent.
# Removing something from the repo also removes the matching symlink or
# assembled file in Claude Code / OpenCode, as long as it was not replaced
# by an own file (COPY=1 copies are left alone, since they look the same
# as an own file).
set -euo pipefail
shopt -s nullglob

REPO="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
TARGET="${1:-both}"
COPY="${COPY:-0}"

CLAUDE="$HOME/.claude"
OPENCODE="${XDG_CONFIG_HOME:-$HOME/.config}/opencode"
MARK="<!-- generated by sync.sh, edit in the repo -->"

place() {   # place <source> <dest>
  local src="$1" dest="$2"
  if [ -e "$dest" ] && [ ! -L "$dest" ] && [ "$COPY" != "1" ]; then
    echo "  skipped, own file exists: $dest"
    return
  fi
  rm -rf "$dest"
  if [ "$COPY" = "1" ]; then
    cp -R "$src" "$dest"
    echo "  copied     $dest"
  else
    ln -s "$src" "$dest"
    echo "  linked     $dest"
  fi
}

assemble_agent() {   # assemble_agent <head> <body> <dest>
  local head="$1" body="$2" dest="$3"
  if [ ! -f "$body" ]; then
    echo "  missing body: $body"
    return
  fi
  if [ -f "$dest" ] && [ ! -L "$dest" ] && ! grep -qF "$MARK" "$dest"; then
    echo "  skipped, own file exists: $dest"
    return
  fi
  rm -f "$dest"
  { cat "$head" "$body"; printf '\n%s\n' "$MARK"; } > "$dest"
  echo "  assembled  $dest"
}

cleanup_links() {   # cleanup_links <dir>  removes symlinks whose target in this repo is gone
  local dir="$1" f target
  for f in "$dir"/*; do
    [ -L "$f" ] || continue
    target="$(readlink "$f")"
    case "$target" in
      "$REPO"/*)
        if [ ! -e "$target" ]; then
          rm -f "$f"
          echo "  removed orphan: $f"
        fi
        ;;
    esac
  done
}

cleanup_assembled() {   # cleanup_assembled <agents dir> <tool>  removes assembled agents whose head or body is gone
  local dir="$1" tool="$2" f n
  for f in "$dir"/*.md; do
    [ -f "$f" ] && [ ! -L "$f" ] || continue
    grep -qF "$MARK" "$f" || continue
    n="$(basename "$f" .md)"
    if [ ! -f "$REPO/targets/$tool/agents/$n.head" ] || [ ! -f "$REPO/agents/$n.md" ]; then
      rm -f "$f"
      echo "  removed orphan: $f"
    fi
  done
}

sync_tool() {   # sync_tool <tool> <base dir>
  local tool="$1" base="$2" f n
  echo "$tool: $base"
  mkdir -p "$base/commands" "$base/agents"

  for f in "$REPO"/commands/*.md "$REPO/targets/$tool"/commands/*.md; do
    place "$f" "$base/commands/$(basename "$f")"
  done

  for f in "$REPO/targets/$tool"/agents/*.md; do
    place "$f" "$base/agents/$(basename "$f")"
  done

  for f in "$REPO/targets/$tool"/agents/*.head; do
    n="$(basename "$f" .head)"
    assemble_agent "$f" "$REPO/agents/$n.md" "$base/agents/$n.md"
  done

  cleanup_links "$base/commands"
  cleanup_links "$base/agents"
  cleanup_assembled "$base/agents" "$tool"
}

# Skills live in one place: Claude Code reads ~/.claude/skills, OpenCode reads it too.
echo "skills: $CLAUDE/skills"
mkdir -p "$CLAUDE/skills"
for d in "$REPO"/skills/*/; do
  place "${d%/}" "$CLAUDE/skills/$(basename "$d")"
done
cleanup_links "$CLAUDE/skills"

case "$TARGET" in
  claude)   sync_tool claude "$CLAUDE" ;;
  opencode) sync_tool opencode "$OPENCODE" ;;
  both)     sync_tool claude "$CLAUDE"; sync_tool opencode "$OPENCODE" ;;
  *)        echo "Unknown target: $TARGET (claude, opencode or both)"; exit 1 ;;
esac

echo "Done. Start a new session so everything is reloaded."
